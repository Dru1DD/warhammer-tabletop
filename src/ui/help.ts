export interface Lesson {
  title: string
  text: (human: PlayerId) => string
  /** `start` = game state when this lesson became current */
  done: (g: GameState, ui: { selectedUnitId: string | null; measure: { a: MeasurePoint | null; b: MeasurePoint | null } }, human: PlayerId, start: TutorialStart) => boolean
}

export interface TutorialStart {
  round: number
  activePlayer: PlayerId
  diceCount: number
}

